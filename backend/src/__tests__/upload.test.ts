describe('detectImageType', () => {
  it('detects jpeg/png/webp from magic bytes', () => {
    expect(detectImageType(JPEG)?.ext).toBe('jpeg');
    expect(detectImageType(PNG)?.ext).toBe('png');
    expect(detectImageType(WEBP)?.ext).toBe('webp');
  });

  it('rejects unknown / truncated buffers', () => {
    expect(detectImageType(Buffer.from([0x00, 0x01, 0x02]))).toBeNull();
    expect(detectImageType(Buffer.alloc(4))).toBeNull();
  });
});

describe('validateImageBuffers', () => {
  it('accepts a valid jpeg', () => {
    const result = validateImageBuffers([{ buffer: JPEG, originalname: 'a.jpg' }]);
    expect(result).toHaveLength(1);
    expect(result[0].ext).toBe('jpeg');
  });

  it('rejects an empty file list', () => {
    expect(() => validateImageBuffers([])).toThrow(AppError);
  });

  it('rejects a spoofed extension (text bytes claiming to be an image)', () => {
    expect(() =>
      validateImageBuffers([{ buffer: Buffer.from('not-an-image'), originalname: 'x.jpg' }]),
    ).toThrow(/JPEG, PNG, or WebP/);
  });

  it('rejects oversize buffers', () => {
    const huge = Buffer.concat([JPEG, Buffer.alloc(IMAGE_LIMITS.maxBytes)]);
    expect(() => validateImageBuffers([{ buffer: huge }])).toThrow(/exceeds/);
  });

  it('rejects more than maxFiles', () => {
    const files = Array.from({ length: IMAGE_LIMITS.maxFiles + 1 }, () => ({ buffer: JPEG }));
    expect(() => validateImageBuffers(files)).toThrow(/No more than/);
  });
});
